const COLORS = {
  panel: "#1a1c22",
  border: "#242530",
  accent: "#1ed760",
  text: "#fff",
  muted: "#9ca3af",
};

const CARD_CONFIG = [
  { key: "balance", label: "Balance" },
  { key: "revenue", label: "Revenue" },
  { key: "expenses", label: "Expenses" },
  { key: "savings", label: "Savings" },
] as const;

function formatCurrency(value: number): string {
  return new Intl.NumberFormat("en-US", {
    style: "currency",
    currency: "USD",
    maximumFractionDigits: 0,
  }).format(value);
}

export default function StatCards() {
  const [summary, setSummary] = useState<Summary | null>(null);
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState<string | null>(null);

  useEffect(() => {
    let cancelled = false;

    async function fetchSummary() {
      try {
        const res = await api.get<Summary>("/transactions/summary");
        if (!cancelled) setSummary(res.data);
      } catch (err: any) {
        if (!cancelled) {
          setError(err?.response?.data?.message || "Failed to load summary");
        }
      } finally {
        if (!cancelled) setLoading(false);
      }
    }

    fetchSummary();
    return () => {
      cancelled = true;
    };
  }, []);

  return (
    <>
      <style>{`
        @media (max-width: 1024px) {
          .stat-grid { grid-template-columns: repeat(2, 1fr) !important; }
        }
        @media (max-width: 640px) {
          .stat-grid { grid-template-columns: 1fr !important; }
        }
      `}</style>
      <div
        className="stat-grid"
        style={{
          display: "grid",
          gridTemplateColumns: "repeat(4, 1fr)",
          gap: 20,
          marginBottom: 32,
        }}
      >
        {CARD_CONFIG.map(({ key, label }) => (
          <div
            key={key}
            style={{
              background: COLORS.panel,
              border: `1px solid ${COLORS.border}`,
              borderRadius: 12,
              padding: 20,
              display: "flex",
              flexDirection: "row",
              alignItems: "center",
              gap: 14,
            }}
          >
            <div
              style={{ width: 40, height: 40, flexShrink: 0 }}
              dangerouslySetInnerHTML={{ __html: ICON_SVGS[key] }}
            />
            <div>
              <div style={{ color: COLORS.muted, fontSize: 13, marginBottom: 4 }}>{label}</div>
              <div style={{ color: COLORS.text, fontSize: 24, fontWeight: 700 }}>
                {loading ? "—" : summary ? formatCurrency(summary[key]) : "$0"}
              </div>
            </div>
          </div>
        ))}
      </div>

      <AlertChip
        open={!!error}
        message={error || ""}
        severity="error"
        onClose={() => setError(null)}
      />
    </>
  );
}